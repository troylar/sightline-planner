#!/usr/bin/env bash
# publish.sh <version>: in a clean release worktree, check out main, refuse unless main's own CI on that commit passed,
# build, run the full suite and every browser suite, publish the page and helpers to the docs folder, npm pack (never
# npm publish), and check the tarball. Everything it does goes to $SIGHTLINE_OUT/rel-<version>/report.txt.
#
# Settings (nothing about a machine or a person lives in this file):
#   SIGHTLINE_RELEASE_DIR  a worktree used only for releases (required)
#   SIGHTLINE_DOCS         the folder the page is published to (required)
#   PLAYWRIGHT             path to node_modules/playwright (required: browser suites are not optional here)
#   SIGHTLINE_OUT          where reports and tarballs go (default: $TMPDIR/sightline-releases)
#   SIGHTLINE_REMOTE       the git remote for the public repository (default: public)
#   SIGHTLINE_REPO         owner/name on GitHub (default: troylar/sightline-planner)
# Private terms come from ~/.config/Sightline/private-terms, the same file tools/check-private.sh reads.
set -u
V=${1:?usage: publish.sh <version>}; H=$(cd "$(dirname "$0")" && pwd)
: "${SIGHTLINE_RELEASE_DIR:?set SIGHTLINE_RELEASE_DIR}" "${SIGHTLINE_DOCS:?set SIGHTLINE_DOCS}" "${PLAYWRIGHT:?set PLAYWRIGHT}"
D=$SIGHTLINE_DOCS; PWM=$PLAYWRIGHT; REMOTE=${SIGHTLINE_REMOTE:-public}; REPO=${SIGHTLINE_REPO:-troylar/sightline-planner}
N=${SIGHTLINE_OUT:-${TMPDIR:-/tmp}/sightline-releases}/rel-$V
rm -rf "$N"; mkdir -p "$N"; R=$N/report.txt; exec > >(tee "$R") 2>&1
bash "$H/test-browser-count.sh" >/dev/null || { echo "BROWSER COUNT SELF-TEST FAILED: not publishing"; exit 1; }
cd "$SIGHTLINE_RELEASE_DIR" || exit 1
# Only build output may differ here; CHANGELOG.md is regenerated by every build. Anything else is a surprise: stop.
other=$(git diff --name-only | grep -vx CHANGELOG.md); [ -z "$other" ] || { echo "UNEXPECTED LOCAL CHANGES: $other"; exit 1; }
git checkout -q -- CHANGELOG.md 2>/dev/null
git fetch -q "$REMOTE" && git checkout -q --detach "$REMOTE/main" || { echo "CHECKOUT FAILED"; exit 1; }
echo "commit: $(git log --oneline -1)"
# Publish only after main's own runs on this commit all concluded success (not just the pull request's).
SHA=$(git rev-parse HEAD); CI=$(gh run list -R "$REPO" --commit "$SHA" --json name,status,conclusion -q '.[] | "\(.name) \(.status) \(.conclusion)"')
echo "main CI on $SHA:"; echo "$CI"
[ -n "$CI" ] && ! echo "$CI" | grep -qv " completed success$" || { echo "MAIN CI NOT ALL SUCCESS YET: not publishing"; exit 1; }
./build.sh 2>&1 | tail -1
git diff --quiet -- CHANGELOG.md || echo "NOTE: the committed CHANGELOG.md is out of date (the build regenerated it); the tarball carries the regenerated one"
[ "$(python3 -c "import json;print(json.load(open('src/releases.json'))[0]['version'])")" = "$V" ] && grep -q "\"version\": \"$V\"" package.json && echo "version $V in releases and package" || { echo "VERSION MISMATCH"; exit 1; }
PLAYWRIGHT=$PWM SIGHTLINE_JOBS=${SIGHTLINE_JOBS:-6} ./test/run.sh > "$N/suite.log" 2>&1; rc=$?; echo "suite exit $rc"; grep -E "harness4 |FAIL" "$N/suite.log" | head -5; [ $rc = 0 ] || exit 1
BROWSER=$(sed -n "s/.*suites=(\([^)]*\)).*/\1/p" test/run.sh); [ -n "$BROWSER" ] || { echo "NO BROWSER LIST IN run.sh"; exit 1; }; echo "browser checks from run.sh: $BROWSER"
BOUT=$(cd test && for t in $BROWSER; do [ -f "$t.js" ] || { echo "$t MISSING"; continue; }; PLAYWRIGHT=$PWM node "$t.js" | tail -1 | sed "s/^/$t /"; done); echo "$BOUT"
# every listed suite must report all passed, and there must be at least one: a quiet step is a failed step
CNT=$(echo "$BOUT" | bash "$H/browser-count.sh" "$BROWSER") || { echo "BROWSER CHECKS: $CNT passed: not publishing"; exit 1; }; echo "browser checks: $CNT passed"
./tools/check-private.sh --all 2>&1 | tail -1
PUBLISH_TO=$D/sightline.html ./build.sh 2>&1 | tail -1
cmp dist/sightline.html "$D/sightline.html" && echo "docs copy matches dist"
echo "--- docs folder sha256"; (cd "$D" && shasum -a 256 sightline.html sightline-app.py sightline-jira-sync.py)
npm pack --dry-run 2>&1 | grep -E "npm notice [0-9.]+[kMB]+ " | sed 's/npm notice //' > "$N/dryrun.txt"
npm pack --pack-destination "$N" 2>&1 | tail -1; T=$(ls "$N"/*.tgz); echo "--- tarball"; shasum -a 256 "$T"; echo "files: $(wc -l < "$N/dryrun.txt")"
grep -qE " test/" "$N/dryrun.txt" && echo "TEST FILES IN PACKAGE" || echo "no test/ in package"
mkdir "$N/u" && tar -xzf "$T" -C "$N/u"; P=$N/u/package
TF=$HOME/.config/Sightline/private-terms
if [ -s "$TF" ]; then pat=$(grep -v '^\s*$' "$TF" | sed 's/[][\.*^$|?+(){}]/\\&/g' | paste -sd'|' -)
  echo "--- private terms (text):"; grep -rlIiE "$pat" "$P"; echo "--- private terms (png):"; for f in $(find "$P" -name "*.png"); do strings "$f" | grep -qiE "$pat" && echo "$f"; done
else echo "--- PRIVATE TERMS FILE MISSING ($TF): not checked"; fi
echo "--- paths and placeholders:"; grep -rnIiE "github\.com/troylar/sightline([^-]|$)|/Users/|/home/[a-z]|customfield_12345" "$P" | cut -c1-160
echo "--- broken links:"; (cd "$P" && grep -rhoE "\]\(([^)#h][^)]*)\)" README.md docs/*.md | sed 's/^](//;s/)$//' | sort -u | while read -r l; do f=${l%%#*}; [ -e "$f" ] || [ -e "docs/$f" ] || echo "missing: $l"; done)
echo "--- smoke:"; mkdir -p "$N/smoke" && cd "$N/smoke" && npm init -y >/dev/null && npm install --no-audit --no-fund "$T" 2>&1 | tail -1 && npx sightline --version && npx sightline install out >/dev/null && HP=$(npx sightline helpers)
for f in sightline-app.py sightline-jira-sync.py; do a=$(shasum -a 256 < "$HP/$f"|cut -c1-64); b=$(shasum -a 256 < "$D/$f"|cut -c1-64); echo "$f $([ "$a" = "$b" ] && echo matches-published || echo DIFFERS)"; done
a=$(shasum -a 256 < out/sightline.html|cut -c1-64); b=$(shasum -a 256 < "$D/sightline.html"|cut -c1-64); echo "sightline.html $([ "$a" = "$b" ] && echo matches-published || echo DIFFERS)"
# A copy with one script changed must be blocked by the page's CSP hashes; the published copy must run.
python3 - <<'PY'
s=open("out/sightline.html",encoding="utf-8").read(); i=s.index("const PLAN_TABS"); open("out/tampered.html","w",encoding="utf-8").write(s[:i]+"const PLAN_TABZ=0;"+s[i:])
PY
cat > "$N/csp.js" <<JS
module.exports = async page => { const out = {};
  for (const f of ["sightline.html", "tampered.html"]) { await page.goto("file://$N/smoke/out/" + f); await page.waitForTimeout(1200);
    out[f] = await page.evaluate(()=>typeof APP_VERSION === "string" ? APP_VERSION : null); }
  return {count:2, errs:[], out}; };
JS
node "$H/drive.js" "$PWM" "$N/csp.js" "$N/csp.json" && echo "browser: $(tr -d ' \n' < "$N/csp.json")"
